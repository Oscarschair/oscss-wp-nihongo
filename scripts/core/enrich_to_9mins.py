def get_stats(t):
    plain = re.sub(r'---.*?---', '', t, flags=re.DOTALL)
    plain = re.sub(r'<[^>]+>', '', plain)
    plain = re.sub(r'\[([^\]]+)\]\([^\)]+\)', r'\1', plain)
    plain = re.sub(r'\s+', '', plain)
    return len(plain), math.ceil(len(plain)/500)

